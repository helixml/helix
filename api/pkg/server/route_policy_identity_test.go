package server

// Authorization policies for the identity routes. See route_auth_policy_test.go
// for the classes; routePolicyFile says which file a new route belongs in.
func init() {
	declareRoutePolicies(map[string]routePolicy{
		"GET /api/v1/oauth/flow/callback":                 public("OAuth provider redirect; the state parameter is matched to a pending flow"),
		"POST /api/v1/auth/register":                      public("account registration (refused when registration or password auth is off)"),
		"GET /api/v1/invitations/{id}/info":               public("invitation landing page; the unguessable invitation id is the credential"),
		"POST /api/v1/invitations/{id}/accept":            handlerAuth("requires a BFF session cookie and CSRF token"),
		"POST /api/v1/auth/login":                         public("password login"),
		"GET /api/v1/auth/callback":                       public("OIDC callback; state and nonce verified"),
		"GET /api/v1/auth/user":                           handlerAuth("returns the session's own user, 401 without one"),
		"GET /api/v1/auth/session":                        handlerAuth("returns the caller's own session, 401 without one"),
		"POST /api/v1/auth/logout":                        public("clears the caller's own session cookie"),
		"GET /api/v1/auth/authenticated":                  public("reports whether the caller is signed in"),
		"POST /api/v1/auth/refresh":                       public("no-op without a refresh cookie; the refresh token is the credential"),
		"POST /api/v1/auth/password-reset":                public("sends a reset email; same answer whether or not the account exists"),
		"POST /api/v1/auth/password-reset-complete":       public("the emailed reset token is the credential"),
		"GET /api/v1/auth/desktop-callback":               handlerAuth("DESKTOP_AUTO_LOGIN_SECRET compared in constant time; 404 when unset"),
		"GET /api/v1/users":                               admin(),
		"POST /api/v1/users":                              admin(),
		"GET /api/v1/oauth/providers":                     user(),
		"POST /api/v1/oauth/providers":                    user(),
		"GET /api/v1/oauth/providers/{id}":                noAuthzHelper("providers are deployment-wide; non-admins see enabled ones without the client secret"),
		"PUT /api/v1/oauth/providers/{id}":                noAuthzHelper("inline user.Admin check"),
		"DELETE /api/v1/oauth/providers/{id}":             noAuthzHelper("inline user.Admin check"),
		"GET /api/v1/oauth/connections":                   user(),
		"GET /api/v1/oauth/connections/{id}":              noAuthzHelper("inline owner check: connection.UserID == user.ID or admin"),
		"DELETE /api/v1/oauth/connections/{id}":           noAuthzHelper("inline owner check: connection.UserID == user.ID or admin"),
		"POST /api/v1/oauth/connections/{id}/refresh":     noAuthzHelper("inline owner check: connection.UserID == user.ID or admin"),
		"GET /api/v1/oauth/connections/{id}/test":         noAuthzHelper("inline owner check: connection.UserID == user.ID"),
		"GET /api/v1/oauth/connections/{id}/repositories": noAuthzHelper("inline owner check: connection.UserID == user.ID or admin"),
		"GET /api/v1/oauth/flow/start/{provider_id}":      noAuthzHelper("starts a flow bound to the caller against a deployment-wide provider"),
		"POST /api/v1/oauth/sharepoint/resolve-site":      user(),
		"POST /api/v1/api_keys":                           user(),
		"GET /api/v1/api_keys":                            user(),
		"DELETE /api/v1/api_keys":                         user(),
		"GET /api/v1/api_keys/check":                      user(),
		"GET /api/v1/users/search":                        object("authorizeOrgMember"),
		"GET /api/v1/users/token-usage":                   user(),
		"GET /api/v1/users/me/guidelines":                 user(),
		"PUT /api/v1/users/me/guidelines":                 user(),
		"GET /api/v1/users/me/guidelines-history":         user(),
		"PUT /api/v1/users/me/color-scheme":               user(),
		"GET /api/v1/users/me/chat-settings":              user(),
		"PUT /api/v1/users/me/chat-settings":              user(),
		"GET /api/v1/users/me/pinned-projects":            user(),
		"GET /api/v1/users/me/pinned-chats":               user(),
		"POST /api/v1/users/me/pinned-chats":              user(),
		"DELETE /api/v1/users/me/pinned-chats":            user(),
		"POST /api/v1/users/me/onboarding":                user(),
		"GET /api/v1/users/{id}":                          object("canViewUserDetails"),
		"GET /api/v1/users/{id}/stats":                    noAuthzHelper("inline admin check"),
		"GET /api/v1/secrets":                             object("authorizeOrgMember"),
		"POST /api/v1/secrets":                            object("authorizeUserToProject"),
		"PUT /api/v1/secrets/{id}":                        object("authorizeUserToProject"),
		"DELETE /api/v1/secrets/{id}":                     object("authorizeUserToProjectByID"),
		"POST /api/v1/auth/password-update":               user(),
		"POST /api/v1/auth/update":                        user(),
	})
}
